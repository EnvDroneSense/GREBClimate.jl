### Preset reference ###
#
# MAINTAINER TOOL. No dataset needed.
#
# Writes test/support/data/preset_reference.jl: what every experiment preset
# imposes, captured from the current code by test/support/presetcapture.jl.
# test/test_presets.jl checks the package against it. Regenerate only when a
# preset is meant to change, and say so in the commit.
#
# `repr` spacing differs between Julia versions: run JuliaFormatter on the
# written file before committing it.
#
# Usage:
#   julia --project=. test/support/preset_reference.jl

include(joinpath(@__DIR__, "imports.jl"))
include(joinpath(@__DIR__, "testutils.jl"))
include(joinpath(@__DIR__, "presetcapture.jl"))

out = joinpath(@__DIR__, "data", "preset_reference.jl")
mkpath(dirname(out))
open(out, "w") do io
    println(io, "# Generated by test/support/preset_reference.jl - do not edit by hand.")
    println(io, "const PRESET_REFERENCE = Dict{Symbol,Any}(")
    for p in PRESETS
        println(io, "    :$p => ", repr(capture_preset(p)), ",")
    end
    println(io, ")")
end
println("wrote $(length(PRESETS)) presets to $out ($(filesize(out)) bytes)")
